package main

import (
	"fmt"
	"log"
	"os"
	"path/filepath"
	"strings"

	"gopkg.in/yaml.v3"
)

// ServiceConfig defines one per-service spec to merge. Each file's paths are already the full
// public paths (prefix included, e.g. /api/v1/catalog/category), so they are copied as they are.
type ServiceConfig struct {
	File string
	Name string
}

// componentKinds are the component maps whose $ref targets are prefixed with the service name
// during the merge, so two services can both define, say, a "Error" schema.
var componentKinds = []string{"schemas", "parameters", "responses", "requestBodies", "headers", "examples"}

// services lists every per-service spec in specs/. A missing file is skipped with a warning.
var services = []ServiceConfig{
	{File: "auth.yml", Name: "Auth"},
	{File: "user_profile.yml", Name: "UserProfile"},
	{File: "profile.yml", Name: "Profile"},
	{File: "catalog.yml", Name: "Catalog"},
	{File: "menu.yml", Name: "Menu"},
	{File: "order.yml", Name: "Order"},
	{File: "gateway.yml", Name: "Gateway"},
	{File: "extensions.yml", Name: "Extensions"},
	{File: "extensions_node.yml", Name: "ExtensionsNode"},
	{File: "marketing.yml", Name: "Marketing"},
	{File: "scheduler.yml", Name: "Scheduler"},
}

// OpenAPISpec is the consolidated document written to specs/openapi.yml.
type OpenAPISpec struct {
	OpenAPI    string                 `yaml:"openapi"`
	Info       map[string]interface{} `yaml:"info"`
	Servers    []interface{}          `yaml:"servers,omitempty"`
	Security   []interface{}          `yaml:"security,omitempty"`
	Components map[string]interface{} `yaml:"components,omitempty"`
	Paths      map[string]interface{} `yaml:"paths,omitempty"`
	Tags       []interface{}          `yaml:"tags,omitempty"`
}

func main() {
	specsDir := "specs"
	outputFile := filepath.Join(specsDir, "openapi.yml")

	if _, err := os.Stat(specsDir); os.IsNotExist(err) {
		log.Fatalf("Error: specs directory not found at %s (run from the repo root)", specsDir)
	}

	fmt.Println("Starting OpenAPI specification merge...")

	if err := mergeSpecs(specsDir, outputFile); err != nil {
		log.Fatalf("Error during merge: %v", err)
	}
}

func newConsolidated() *OpenAPISpec {
	components := map[string]interface{}{
		"securitySchemes": map[string]interface{}{
			"bearerAuth": map[string]interface{}{
				"type":         "http",
				"scheme":       "bearer",
				"bearerFormat": "JWT",
				"description":  "JWT access token from the dh-auth login flow. Send as: Authorization: Bearer <token>",
			},
		},
	}
	for _, kind := range componentKinds {
		components[kind] = map[string]interface{}{}
	}
	return &OpenAPISpec{
		OpenAPI: "3.0.1",
		Info: map[string]interface{}{
			"title": "Dhaam Platform API - Consolidated",
			"description": `Consolidated OpenAPI 3.0 specification for the DhaamAI backend services.

Paths are full public paths (for example /api/v1/orders/...).
Set the Apidog environment variable baseUrl and use it as the server. See specs/AUTOMATION.md
for environments, the login flow, and the order of calls.

Generated by merge_specs.go from the per-service files in specs/. Edit those files, not this one.`,
			"version": "2.0.0",
		},
		// Only the placeholder: each environment's host is set in Apidog, never in this repo.
		Servers:    []interface{}{map[string]interface{}{"url": "{{baseUrl}}", "description": "Public API base URL (environment variable baseUrl)"}},
		Security:   []interface{}{map[string]interface{}{"bearerAuth": []interface{}{}}},
		Components: components,
		Paths:      map[string]interface{}{},
		Tags:       []interface{}{},
	}
}

func mergeSpecs(specsDir, outputFile string) error {
	consolidated := newConsolidated()

	for _, service := range services {
		servicePath := filepath.Join(specsDir, service.File)

		if _, err := os.Stat(servicePath); os.IsNotExist(err) {
			fmt.Printf("Warning: %s not found, skipping...\n", service.File)
			continue
		}

		fmt.Printf("Processing %s service from %s...\n", service.Name, service.File)

		serviceSpec, err := loadYAML(servicePath)
		if err != nil {
			return fmt.Errorf("failed to load %s: %w", service.File, err)
		}

		updateRefs(serviceSpec, service.Name)
		mergeComponents(consolidated, serviceSpec, service.Name)
		if err := mergePaths(consolidated, serviceSpec, service.File); err != nil {
			return err
		}
		mergeTags(consolidated, serviceSpec, service.Name)

		fmt.Printf("Merged %s service\n", service.Name)
	}

	addCommonSchemas(consolidated)

	fmt.Printf("\nWriting consolidated spec to %s...\n", outputFile)

	if err := writeYAML(outputFile, consolidated); err != nil {
		return fmt.Errorf("failed to write output: %w", err)
	}

	printSummary(consolidated, outputFile)

	return nil
}

func loadYAML(path string) (map[string]interface{}, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}

	var spec map[string]interface{}
	if err := yaml.Unmarshal(data, &spec); err != nil {
		return nil, err
	}

	return spec, nil
}

func writeYAML(path string, data interface{}) error {
	f, err := os.Create(path)
	if err != nil {
		return err
	}
	defer f.Close()

	encoder := yaml.NewEncoder(f)
	encoder.SetIndent(2)
	defer encoder.Close()

	return encoder.Encode(data)
}

// updateRefs rewrites local $refs to a component of any kind in componentKinds so they point at
// the service-prefixed name that mergeComponents stores.
func updateRefs(obj interface{}, serviceName string) {
	switch v := obj.(type) {
	case map[string]interface{}:
		for key, value := range v {
			if key == "$ref" {
				str, ok := value.(string)
				if !ok {
					continue
				}
				for _, kind := range componentKinds {
					prefix := "#/components/" + kind + "/"
					if strings.HasPrefix(str, prefix) {
						name := strings.TrimPrefix(str, prefix)
						v[key] = fmt.Sprintf("%s%s_%s", prefix, serviceName, name)
						break
					}
				}
			} else {
				updateRefs(value, serviceName)
			}
		}
	case []interface{}:
		for _, item := range v {
			updateRefs(item, serviceName)
		}
	}
}

func mergeComponents(target *OpenAPISpec, source map[string]interface{}, serviceName string) {
	sourceComponents, ok := source["components"].(map[string]interface{})
	if !ok {
		return
	}

	targetComponents := target.Components

	for _, kind := range componentKinds {
		items, ok := sourceComponents[kind].(map[string]interface{})
		if !ok {
			continue
		}
		targetItems := targetComponents[kind].(map[string]interface{})
		for name, def := range items {
			targetItems[fmt.Sprintf("%s_%s", serviceName, name)] = def
		}
	}

	// Security schemes are shared, not prefixed; first definition wins (all specs define bearerAuth alike).
	if secSchemes, ok := sourceComponents["securitySchemes"].(map[string]interface{}); ok {
		targetSecSchemes := targetComponents["securitySchemes"].(map[string]interface{})
		for schemeName, schemeDef := range secSchemes {
			if _, exists := targetSecSchemes[schemeName]; !exists {
				targetSecSchemes[schemeName] = schemeDef
			}
		}
	}
}

// mergePaths copies paths unchanged (they are already full public paths) and fails on a collision,
// so two services cannot silently overwrite each other's operations.
func mergePaths(target *OpenAPISpec, source map[string]interface{}, file string) error {
	sourcePaths, ok := source["paths"].(map[string]interface{})
	if !ok {
		return nil
	}

	for path, pathDef := range sourcePaths {
		if _, exists := target.Paths[path]; exists {
			return fmt.Errorf("path %s in %s collides with another service", path, file)
		}
		target.Paths[path] = pathDef
	}
	return nil
}

func mergeTags(target *OpenAPISpec, source map[string]interface{}, serviceName string) {
	sourceTags, ok := source["tags"].([]interface{})
	if !ok {
		return
	}

	for _, tag := range sourceTags {
		if tagMap, ok := tag.(map[string]interface{}); ok {
			prefixedTag := map[string]interface{}{
				"name": fmt.Sprintf("%s - %s", serviceName, tagMap["name"]),
			}
			if desc, exists := tagMap["description"]; exists {
				prefixedTag["description"] = desc
			}
			target.Tags = append(target.Tags, prefixedTag)
		}
	}
}

func addCommonSchemas(target *OpenAPISpec) {
	schemas := target.Components["schemas"].(map[string]interface{})

	schemas["SuccessResponse"] = map[string]interface{}{
		"type": "object",
		"properties": map[string]interface{}{
			"success": map[string]interface{}{
				"type":    "boolean",
				"example": true,
			},
			"data": map[string]interface{}{
				"type":        "object",
				"description": "Response payload (varies by endpoint)",
			},
			"meta": map[string]interface{}{
				"type":        "object",
				"description": "Metadata (pagination, timestamps, etc.)",
			},
		},
	}

	schemas["ErrorResponse"] = map[string]interface{}{
		"type": "object",
		"properties": map[string]interface{}{
			"success": map[string]interface{}{
				"type":    "boolean",
				"example": false,
			},
			"error": map[string]interface{}{
				"type": "object",
				"properties": map[string]interface{}{
					"code": map[string]interface{}{
						"type":        "string",
						"description": "Error code",
					},
					"message": map[string]interface{}{
						"type":        "string",
						"description": "Human-readable error message",
					},
				},
			},
		},
	}
}

func printSummary(spec *OpenAPISpec, outputFile string) {
	schemas := spec.Components["schemas"].(map[string]interface{})
	params := spec.Components["parameters"].(map[string]interface{})

	fmt.Println("\n" + strings.Repeat("=", 60))
	fmt.Println("Merge completed successfully!")
	fmt.Println(strings.Repeat("=", 60))
	fmt.Println("Summary:")
	fmt.Printf("   - Schemas: %d\n", len(schemas))
	fmt.Printf("   - Parameters: %d\n", len(params))
	fmt.Printf("   - Paths: %d\n", len(spec.Paths))
	fmt.Printf("   - Tags: %d\n", len(spec.Tags))
	fmt.Printf("\nOutput file: %s\n", outputFile)
	fmt.Println(strings.Repeat("=", 60))
}
